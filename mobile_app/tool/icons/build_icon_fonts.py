"""Builds the Anchor Box icon fonts and lib/core/theme/app_icons.dart.

Icons come from Phosphor (MIT, https://phosphoricons.com). Only the glyphs
listed in icons.json are kept, so each font is a few kilobytes instead of
the ~500 KB full Phosphor fonts.

Usage (Python with fonttools installed):
    python tool/icons/build_icon_fonts.py [path/to/phosphor_flutter-x.y.z]

Without an argument the newest phosphor_flutter in the pub cache is used.
After editing icons.json, run this script and commit the fonts and the
generated Dart file.
"""
import glob
import json
import os
import re
import shutil
import subprocess
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.normpath(os.path.join(HERE, '..', '..'))
FONT_DIR = os.path.join(APP, 'assets', 'fonts', 'icons')
DART_OUT = os.path.join(APP, 'lib', 'core', 'theme', 'app_icons.dart')

# Glyphs drawn off-centre in Phosphor that sit in symmetric slots (tab bar).
OPTICAL_CENTER = {'password'}

STYLES = {
    'regular': ('Phosphor.ttf', 'phosphor_icons_regular.dart', 'AnchorIconsRegular'),
    'fill': ('Phosphor-Fill.ttf', 'phosphor_icons_fill.dart', 'AnchorIconsFill'),
    'bold': ('Phosphor-Bold.ttf', 'phosphor_icons_bold.dart', 'AnchorIconsBold'),
}


def phosphor_dir():
    if len(sys.argv) > 1:
        return sys.argv[1]
    cache = os.environ.get('PUB_CACHE') or os.path.join(
        os.environ.get('LOCALAPPDATA', os.path.expanduser('~')), 'Pub', 'Cache')
    found = sorted(glob.glob(os.path.join(cache, 'hosted', 'pub.dev', 'phosphor_flutter-*')))
    if not found:
        sys.exit('phosphor_flutter not found in the pub cache; pass its path.')
    return found[-1]


def codepoints(source_dart):
    text = open(source_dart, encoding='utf-8').read()
    return {name: int(code, 16) for name, code in
            re.findall(r'static const (\w+) = PhosphorFlatIconData\((0x[0-9a-fA-F]+)', text)}


def main():
    root = phosphor_dir()
    spec = json.load(open(os.path.join(HERE, 'icons.json'), encoding='utf-8'))
    os.makedirs(FONT_DIR, exist_ok=True)

    resolved = {}
    for style, (font_file, dart_file, family) in STYLES.items():
        names = {phosphor for (s, phosphor) in spec.values() if s == style}
        if not names:
            continue
        table = codepoints(os.path.join(root, 'lib', 'src', dart_file))
        missing = sorted(n for n in names if n not in table)
        if missing:
            sys.exit(f'Unknown {style} icons: {missing}')

        font = TTFont(os.path.join(root, 'lib', 'fonts', font_file))
        options = subset.Options()
        options.name_IDs = ['*']
        options.notdef_outline = True
        subsetter = subset.Subsetter(options)
        subsetter.populate(unicodes=[table[n] for n in names])
        subsetter.subset(font)
        center_glyphs(font, [table[n] for n in names & OPTICAL_CENTER])
        fix_side_bearings(font)
        out =os.path.join(FONT_DIR, f'{family}.ttf')
        font.save(out)
        print(f'{family}: {len(names)} glyphs, {os.path.getsize(out)} bytes')
        for name, (s, phosphor) in spec.items():
            if s == style:
                resolved[name] = (table[phosphor], family)

    lines = [
        '// GENERATED by tool/icons/build_icon_fonts.py from tool/icons/icons.json.',
        '// Do not edit by hand. Glyphs: Phosphor Icons (MIT).',
        '',
        "import 'package:flutter/widgets.dart';",
        '',
        '/// Every icon of the app, named by meaning. Outline variants are the',
        '/// default; `*Fill` variants mark the selected / active state.',
        'abstract final class AppIcons {',
    ]
    for name, (code, family) in spec_order(spec, resolved):
        lines.append(f"  static const IconData {name} = IconData(0x{code:x}, fontFamily: '{family}');")
    lines.append('}')
    with open(DART_OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    dart = shutil.which('dart')
    if dart:
        subprocess.run([dart, 'format', DART_OUT], check=False, capture_output=True)
    print(f'wrote {os.path.relpath(DART_OUT, APP)} with {len(resolved)} icons')


def center_glyphs(font, codes):
    glyf, cmap = font['glyf'], font.getBestCmap()
    for code in codes:
        name = cmap[code]
        glyph = glyf[name]
        glyph.recalcBounds(glyf)
        advance, _ = font['hmtx'][name]
        shift = round((advance - glyph.xMax - glyph.xMin) / 2)
        coords = glyph.getCoordinates(glyf)[0]
        coords.translate((shift, 0))


def fix_side_bearings(font):
    """Phosphor stores xMin = 0 for every glyph while its outlines start
    further right. Subsetting recomputes the bounding boxes, so the left side
    bearing must follow, or renderers shift every icon to the left."""
    glyf, hmtx = font['glyf'], font['hmtx']
    for name in font.getGlyphOrder():
        glyph = glyf[name]
        if glyph.numberOfContours == 0:
            continue
        glyph.recalcBounds(glyf)
        advance, _ = hmtx[name]
        hmtx[name] = (advance, glyph.xMin)


def spec_order(spec, resolved):
    return [(name, resolved[name]) for name in spec]


if __name__ == '__main__':
    main()
